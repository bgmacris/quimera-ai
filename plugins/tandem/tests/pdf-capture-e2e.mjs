#!/usr/bin/env node
// pdf-capture-e2e.mjs — the REAL MCP through tandem's launcher: PDFs that reach the agent's tab are saved
// as they arrive and the tool's result says where — on the session's very first call with several tabs
// open, a form POST (no cache, a GET returns another document), a plain GET, an `attachment` download,
// blob: PDFs (same tab and new tab), a PDF framed inside a cross-origin iframe — while ordinary pages go
// through untouched and forged binding calls write nothing.
// Needs tandem's Chrome up on TANDEM_CDP_PORT (tests/e2e.sh), TANDEM_DATA_DIR, and the fixture site.
// Usage: node tests/pdf-capture-e2e.mjs <site-url>   (exit 0 = green)
import { spawn } from 'node:child_process';
import { existsSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const SITE = process.argv[2];
const launcher = fileURLToPath(new URL('../scripts/mcp-launch.mjs', import.meta.url));
let pass = 0; let fail = 0;
const ok = (desc, cond, extra = '') => {
  if (cond) { pass++; process.stdout.write(`  ✓ ${desc}\n`); }
  else { fail++; process.stdout.write(`  ✗ ${desc}${extra ? ` — ${extra}` : ''}\n`); if (process.env.GITHUB_ACTIONS) process.stdout.write(`::error title=pdf-capture-e2e::${desc}\n`); }
};

const p = spawn(process.execPath, [launcher], { env: { ...process.env, TANDEM_FOCUS_LINGER_MS: '2000' }, stdio: ['pipe', 'pipe', 'inherit'] });
let buf = ''; const waiters = new Map(); let id = 0;
p.stdout.on('data', (d) => {
  buf += d; let i;
  while ((i = buf.indexOf('\n')) >= 0) { const l = buf.slice(0, i); buf = buf.slice(i + 1); try { const m = JSON.parse(l); waiters.get(m.id)?.(m); } catch {} }
});
const rpc = (method, params, ms = 120000) => new Promise((res, rej) => {
  const n = ++id; waiters.set(n, res); p.stdin.write(JSON.stringify({ jsonrpc: '2.0', id: n, method, params }) + '\n');
  setTimeout(() => rej(new Error(`${method} timeout`)), ms);
});
const text = (r) => (r.result?.content || []).map((c) => c.text || '').join('\n');
const call = async (name, args) => text(await rpc('tools/call', { name, arguments: args }));
// The note's saved file and whether it holds what the fixture served (its text is in the raw PDF stream).
function saved(t, marker) {
  const path = t.match(/saved to (\S+\.pdf) \(/)?.[1];
  const bytes = path && existsSync(path) ? readFileSync(path) : null;
  return { path, ok: !!bytes && bytes.subarray(0, 5).toString('latin1') === '%PDF-' && bytes.toString('latin1').includes(`(${marker})`) };
}

console.log('pdf capture — PDFs reaching the agent\'s tab, through the real MCP');
try {
  await rpc('initialize', { protocolVersion: '2025-06-18', capabilities: {}, clientInfo: { name: 'pdf-capture-e2e', version: '0' } });
  p.stdin.write(JSON.stringify({ jsonrpc: '2.0', method: 'notifications/initialized' }) + '\n');
  const props = (await rpc('tools/list', {})).result.tools.find((t) => t.name === 'browser_click').inputSchema.properties;
  const key = props.target ? 'target' : 'ref';
  const tabs = (await (await import('../scripts/cdp.mjs')).listPages()).length;
  const first = await call('browser_navigate', { url: `${SITE}/doc.pdf?first=1` });
  ok(`the session's FIRST call, ${tabs} tabs open: captured (the proxy asked the MCP which tab is its own)`, tabs > 1 && saved(first, 'Hello tandem').ok, first.slice(-300));
  const home = await call('browser_navigate', { url: `${SITE}/pdf-start` });
  ok('an ordinary page: no note', !home.includes('tandem: PDF captured') && home.includes(`Page URL: ${SITE}/pdf-start`));
  const gen = (await call('browser_snapshot', {})).match(/button "Generate" \[ref=(\w+)\]/)?.[1];
  const post = await call('browser_click', { element: 'Generate', [key]: gen });
  const sp = saved(post, 'Generated by POST');
  ok('a PDF from a form POST: captured, the result says where', post.includes('### tandem: PDF captured') && post.includes(`POST ${SITE}/gen-pdf`) && sp.ok, post.slice(-400));
  const get = await call('browser_navigate', { url: `${SITE}/doc.pdf` });
  ok('a PDF by GET: captured', get.includes(`GET ${SITE}/doc.pdf`) && saved(get, 'Hello tandem').ok, get.slice(-400));
  ok('captured → no "not captured" hint', !get.includes('was not captured'));
  await call('browser_navigate', { url: `${SITE}/pdf-start` });
  const dl = (await call('browser_snapshot', {})).match(/link "Download" \[ref=(\w+)\]/)?.[1];
  let attach = await call('browser_click', { element: 'Download', [key]: dl });
  if (!attach.includes('PDF captured')) attach += await call('browser_snapshot', {});   // a note that arrives late rides on the next result
  const sa = saved(attach, 'Downloaded');
  ok('an attachment download: captured, named from Content-Disposition', attach.includes(`${SITE}/download-pdf`) && sa.ok && /factura_7\.pdf$/.test(sa.path || ''), attach.slice(-400));
  await call('browser_navigate', { url: `${SITE}/pdf-blob` });
  const snap = await call('browser_snapshot', {});
  let nt = await call('browser_click', { element: 'New tab', [key]: snap.match(/button "New tab" \[ref=(\w+)\]/)?.[1] });
  if (!nt.includes('PDF captured')) nt += await call('browser_snapshot', {});
  ok('a blob: PDF opened in a new tab: captured', nt.includes('a blob: PDF made by the page') && saved(nt, 'Blob PDF').ok, nt.slice(-300));
  await call('browser_tabs', { action: 'select', index: 0 }).catch(() => {});
  await call('browser_navigate', { url: `${SITE}/pdf-blob` });
  const snap2 = await call('browser_snapshot', {});
  let st = await call('browser_click', { element: 'Same tab', [key]: snap2.match(/button "Same tab" \[ref=(\w+)\]/)?.[1] });
  if (!st.includes('PDF captured')) st += await call('browser_snapshot', {});
  ok('a blob: PDF the page navigates to (its URL dies with the page): captured', st.includes('a blob: PDF made by the page') && saved(st, 'Blob PDF').ok, st.slice(-300));
  await call('browser_navigate', { url: `${SITE}/pdf-blob` });
  const native = await call('browser_evaluate', { function: '() => Function.prototype.toString.call(URL.createObjectURL)' });
  ok('the createObjectURL wrapper still reads as native code', native.includes('[native code]'), native.slice(0, 200));
  const snap3 = await call('browser_snapshot', {});
  let bu = await call('browser_click', { element: 'Big untyped', [key]: snap3.match(/button "Big untyped" \[ref=(\w+)\]/)?.[1] });
  if (!bu.includes('PDF captured')) bu += await call('browser_snapshot', {});
  ok('a big UNTYPED blob: PDF the page navigates to at once: captured (sync sniff)', bu.includes('a blob: PDF made by the page') && saved(bu, 'Big untyped').ok, bu.slice(-300));
  let fr = await call('browser_navigate', { url: `${SITE}/frame-outer` });
  if (!fr.includes('nested.pdf')) fr += await call('browser_snapshot', {});
  ok('a PDF framed inside a cross-origin iframe: captured', /GET http:\/\/localhost:\d+\/nested\.pdf/.test(fr) && saved(fr, 'Nested').ok, fr.slice(-300));
  const forge = await call('browser_navigate', { url: `${SITE}/forge` });
  const forge2 = await call('browser_snapshot', {});
  ok('forged binding calls (bad URL, not a PDF, not JSON): nothing saved', !(forge + forge2).includes('PDF captured'));
  const plain = await call('browser_navigate', { url: `${SITE}/` });
  ok('after all that, ordinary navigation still works, no note', plain.includes(`Page URL: ${SITE}/`) && !plain.includes('PDF captured'), plain.slice(0, 300));
} catch (e) { ok(`no exception (${e.message})`, false); } finally { p.kill(); }
process.stdout.write(`pdf-capture-e2e: ${pass} ok, ${fail} failures\n`);
process.exit(fail ? 1 : 0);
